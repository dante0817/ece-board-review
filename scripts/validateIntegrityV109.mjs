const cache=new Map();
const load=(rel)=>{
  const full=path.resolve(root,rel);
  if(cache.has(full))return cache.get(full).exports;
  const source=readFileSync(full,'utf8');
  const transformed=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  const mod={exports:{}};cache.set(full,mod);
  new Function('require','module','exports',transformed)((name)=>{
    if(name.startsWith('.'))return load(path.relative(root,path.resolve(path.dirname(full),name+'.ts')));
    return require(name);
  },mod,mod.exports);
  return mod.exports;
};
