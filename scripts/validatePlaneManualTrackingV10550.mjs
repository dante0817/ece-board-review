/** Test the actual shared TypeScript storage implementation, not a model of its regex. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const source=fs.readFileSync(new URL('../src/domain/learn/manualLearnTracking.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const module={exports:{}};
new Function('module','exports',code)(module,module.exports);
const t=module.exports;
const data=new Map();
globalThis.localStorage={getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value)};
globalThis.window={dispatchEvent:()=>{}};
const old={reviewCount:2,selfStatus:'studying',needsReview:false,lastReviewedAt:'2026-10-01T10:00:00.000Z',updatedAt:'2026-10-01T10:00:00.000Z'};
const fixture={schemaVersion:1,records:{'geo-solid-036':old,'alg-real-numbers':{...old}}};
localStorage.setItem(t.MANUAL_LEARN_STORAGE_KEY,JSON.stringify(fixture));
assert(t.validateManualLearnStore(t.readManualLearnStore()));
assert(t.isManualTrackingId('geo-solid-036'));
assert(t.isManualTrackingId('geo-plane-001'));
assert(t.isManualTrackingId('alg-real-numbers'));
assert(t.isManualTrackingId('trig-topic-01'));
assert(!t.isManualTrackingId('geo-plane-other'));
const planeChild=t.lessonCardTrackingId('geo-plane-001','GEO-001-concept');
const solidChild=t.lessonCardTrackingId('geo-solid-036','GEO-036-concepts');
assert.equal(planeChild,'geo-plane-001--unit-geo-001-concept');
assert.equal(solidChild,'geo-solid-036--unit-geo-036-concepts');
assert(t.isManualTrackingId(planeChild));assert(t.isManualTrackingId(solidChild));
assert(t.setManualReadMilestone('geo-plane-001',2,true));
assert(t.setManualReadMilestone(planeChild,3,true));
assert(t.setManualReadMilestone(solidChild,1,true));
const after=t.readManualLearnStore();
assert.equal(after.schemaVersion,1);
assert.deepEqual(after.records['geo-solid-036'],old);
assert.deepEqual(after.records['alg-real-numbers'],old);
assert.equal(after.records['geo-plane-001'].reviewCount,2);
assert.equal(after.records[planeChild].reviewCount,3);
assert.equal(after.records[solidChild].reviewCount,1);
assert.throws(()=>t.lessonCardTrackingId('invalid','GEO-001-concept'));
assert.equal(t.setManualReadMilestone('geo-plane-9999',1,true),false);
console.log('PASS Plane+Solid study tracking: old records unchanged, independent parent/section IDs, schema v1, legacy Algebra/Trigonometry scopes still accepted.');
